export const QATECH_LOGO = Buffer.from(LOGO_BASE64, "base64");
const ASPECT = 245 / 119;

/** Is this organisation QA Tech, whose logo this is? */
export const isQaTech = (shortName: string, legalName = "") =>
  /\bqa\s*tech\b/i.test(`${shortName} ${legalName}`);

/**
 * QA Tech's logo, `height` points tall at (x, y), or for another organisation
 * its name as text. Returns the width used.
 */
export function brandMark(
  doc: Doc,
  org: { shortName: string; legalName: string },
  x: number,
  y: number,
  height: number,
): number {
  if (isQaTech(org.shortName, org.legalName)) {
    doc.image(QATECH_LOGO, x, y, { height });
    return height * ASPECT;
  }
  const name = org.shortName || org.legalName;
  doc
    .font("Helvetica-Bold")
    .fontSize(height * 0.4)
    .fillColor("#1f3a68")
    .text(name, x, y + height * 0.15, { lineBreak: false });
  return doc.widthOfString(name);
}
